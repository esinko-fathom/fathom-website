// api/report.js
// Vercel serverless function — Emails ROI PDF report
// Requires RESEND_API_KEY environment variable in Vercel project settings

export default async function handler(req, res) {
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }

  const { name, email, company, pdfBase64 } = req.body || {};

  if (!name || !email || !pdfBase64) {
    return res.status(400).json({ error: 'Missing required fields (name, email, pdfBase64)' });
  }

  const RESEND_API_KEY = process.env.RESEND_API_KEY;
  if (!RESEND_API_KEY) {
    console.error('RESEND_API_KEY is not set');
    return res.status(500).json({ error: 'Email service not configured' });
  }

  try {
    const response = await fetch('https://api.resend.com/emails', {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${RESEND_API_KEY}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        from: 'Fathom Website <notify@fathom-usa.com>',
        to: ['info@fathom-usa.com'],
        reply_to: email,
        subject: `ROI Report generated by ${name}${company ? ' (' + company + ')' : ''}`,
        html: `
          <h2>New ROI Report Generated</h2>
          <p><strong>Name:</strong> ${name}</p>
          <p><strong>Email:</strong> ${email}</p>
          <p><strong>Company:</strong> ${company || '—'}</p>
          <p>The full PDF report is attached.</p>
        `,
        attachments: [
          {
            filename: `Fathom_ROI_Report_${(company || name || 'Report').replace(/[^a-zA-Z0-9]/g, '_')}.pdf`,
            content: pdfBase64,
          },
        ],
      }),
    });

    const data = await response.json();

    if (!response.ok) {
      console.error('Resend error:', data);
      return res.status(500).json({ error: 'Failed to send email', details: data });
    }

    return res.status(200).json({ success: true, id: data.id });
  } catch (err) {
    console.error(err);
    return res.status(500).json({ error: 'Server error' });
  }
}
